test("NIC preparation validates PIN, vehicle, date, quantity and Part A semantics", async () => {
  await withInvoice(async ({ invoice, preparation }) => {
    assert.throws(() => normalizePreparation(invoice, { ...preparation, seller: { ...preparation.seller, pincode: "123" } }), /six-digit PIN/);
    const noVehicle = { ...preparation, transport: { ...preparation.transport, vehicleNo: "" } };
    assert.throws(() => ewaybillDocument(invoice, noVehicle), /road vehicle/);
    const partA = ewaybillDocument(invoice, { ...noVehicle, transport: { ...noVehicle.transport, partAOnly: true, transporterId: "23ABCDE1234F1Z8" } });
    assert.equal(partA.transMode, "");
    assert.equal(partA.vehicleNo, "");
    const future = new Date(`${invoice.date}T12:00:00Z`);
    future.setUTCDate(future.getUTCDate() + 181);
    assert.throws(() => ewaybillDocument(invoice, preparation, future.toISOString().slice(0, 10)), /preceding 180 days/);
    const granular = structuredClone(invoice);
    granular.items[0].quantity = "1.000001";
    assert.throws(() => irpBulk(granular, preparation), /three|3 decimal/);
    assert.throws(() => ewaybillDocument(granular, preparation), /two|2 decimal/);
    assert.throws(() => irpBulk({ ...invoice, reverseCharge: true }, preparation), /Reverse-charge exchange/);
  });
});

