// The reference below is the public NIC documentation example, never generated by Financer.
// Synthetic tokens use a local test key and must always remain unverified imported reports.
const PUBLIC_SAMPLE_IRN = "11f8ef701fe294d4a14aad0b12457e62775d0fdc41a0acf05b74fbb2ddc47acb";
const { privateKey, publicKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
const makeGstin = (state, pan = "ABCDE1234F") => {
  const prefix = `${state}${pan}1Z`;
  return prefix + gstinCheckDigit(prefix);
};
function token(document, header = {}) {
  const encodedHeader = Buffer.from(JSON.stringify({ alg: "RS256", typ: "JWT", ...header })).toString("base64url");
  const encodedPayload = Buffer.from(JSON.stringify({ data: JSON.stringify(document), iss: "SYNTHETIC-LOCAL-TEST" })).toString("base64url");
  const data = `${encodedHeader}.${encodedPayload}`;
  return `${data}.${sign("RSA-SHA256", Buffer.from(data), privateKey).toString("base64url")}`;
}
function resultFor(invoice, preparation, alterDocument = document => document, alterQr = document => document) {
  const date = `${invoice.date} 12:00:00`;
  const document = alterDocument({ ...irpBulk(invoice, preparation)[0], Irn: PUBLIC_SAMPLE_IRN });
  const maximum = Math.max(...invoice.items.map(item => item.taxablePaise));
  const qr = alterQr({ SellerGstin: invoice.registration.gstin, BuyerGstin: invoice.party.gstin || "URP", DocNo: invoice.number, DocTyp: document.DocDtls.Typ, DocDt: document.DocDtls.Dt, TotInvVal: invoice.totals.totalPaise / 100, ItemCnt: invoice.items.length, MainHsnCode: invoice.items.find(item => item.taxablePaise === maximum).hsnSac, Irn: PUBLIC_SAMPLE_IRN, IrnDt: invoice.date });
  return { AckNo: "112010800018362", AckDt: date, Irn: PUBLIC_SAMPLE_IRN, Status: "ACT", SignedInvoice: token(document), SignedQRCode: token(qr) };
}
async function withInvoice(run, options = {}) {
  const dataDir = await mkdtemp(path.join(tmpdir(), "financer-exchange-"));
  const store = createStore(dataDir);
  try {
    const { company } = await store.create({ name: "Exchange Synthetic Books", booksFrom: "2025-04-01" });
    const { registration } = await store.saveGstMaster(company.id, "registration", { name: "Synthetic Supplier", gstin: makeGstin("23"), stateCode: "23", address: "Synthetic supplier address", pincode: "462001" });
    const { party } = await store.saveGstMaster(company.id, "party", { name: "Synthetic Recipient", gstin: options.unregistered ? "" : makeGstin("27", "PQRST5678L"), stateCode: "27", address: "Synthetic recipient address", pincode: "400001", kind: "customer" });
    const { item } = await store.saveGstMaster(company.id, "item", { name: "Synthetic Goods", kind: "goods", hsnSac: "8541", unit: "NOS", pricePaise: 10000, gstRateBps: 1800, openingQuantity: "10" });
    const { invoice } = await store.passGstInvoice(company.id, { type: "Sales", registrationId: registration.id, partyId: party.id, date: todayISO(), placeOfSupply: "27", pricing: options.inclusive ? "inclusive" : "exclusive", items: [{ itemId: item.id, quantity: "2", unitPricePaise: options.inclusive ? 11800 : 10000 }] });
    const preparation = exchangeDefaults(invoice);
    preparation.seller.location = "Bhopal";
    preparation.buyer.location = "Mumbai";
    preparation.transport.distanceKm = 700;
    preparation.transport.vehicleNo = "MP04AB1234";
    await run({ store, dataDir, company, invoice, preparation });
  } finally { await rm(dataDir, { recursive: true, force: true }); }
}

test("IRP bulk and NIC EWB JSON preserve exact invoice fields and amounts", async () => {
  await withInvoice(async ({ invoice, preparation }) => {
    const bulk = irpBulk(invoice, preparation);
    assert.equal(bulk.length, 1);
    assert.equal(bulk[0].Version, "1.1");
    assert.equal(bulk[0].TranDtls.SupTyp, "B2B");
    assert.equal(bulk[0].TranDtls.RegRev, "N");
    assert.equal(bulk[0].DocDtls.No, invoice.number);
    assert.equal(bulk[0].ValDtls.AssVal, 200);
    assert.equal(bulk[0].ValDtls.IgstVal, 36);
    assert.equal(bulk[0].ValDtls.TotInvVal, 236);
    assert.equal(Object.hasOwn(bulk[0], "Irn"), false);
    const ewb = ewaybillDocument(invoice, preparation);
    assert.equal(ewb.docNo, invoice.number);
    assert.equal(ewb.fromGstin, invoice.registration.gstin);
    assert.equal(ewb.toGstin, invoice.party.gstin);
    assert.equal(ewb.totInvValue, 236);
    assert.equal(ewb.igstValue, 36);
    assert.equal(ewb.transactionType, 1);
    assert.equal(ewb.itemList[0].taxableAmount, 200);
    assert.equal(ewb.vehicleNo, "MP04AB1234");
  });
});

test("a mixed invoice sends services to IRP and restricts standalone movement and evidence to goods", async () => {
  await withInvoice(async ({store,company,invoice:base,preparation}) => {
    const {item:service}=await store.saveGstMaster(company.id,"item",{name:"Synthetic design service",kind:"service",hsnSac:"998391",unit:"OTH",gstRateBps:1800,pricePaise:30000});
    const post=items=>store.passGstInvoice(company.id,{type:"Sales",registrationId:base.registrationId,partyId:base.partyId,date:base.date,placeOfSupply:base.placeOfSupply,items});
    const {invoice}=await post([{itemId:base.items[0].itemId,quantity:"2",unitPricePaise:10000},{itemId:service.id,quantity:"1"}]);
    const [irp]=irpBulk(invoice,preparation);
    assert.deepEqual(irp.ItemList.map(row=>[row.HsnCd,row.IsServc]),[["8541","N"],["998391","Y"]]);
    assert.equal(irp.ValDtls.TotInvVal,590);
    const request=ewaybillDocument(invoice,preparation);
    assert.deepEqual(request.itemList.map(row=>[row.hsnCode,row.quantity,row.taxableAmount]),[[8541,2,200]]);
    assert.deepEqual([request.totalValue,request.igstValue,request.totInvValue],[200,36,236]);
    const result={ewayBillNo:"123456789012",ewayBillDate:"08/11/2026 12:00:00 PM"};
    assert.equal(acknowledgementRecord(invoice,{kind:"ewaybill",result,submittedRequest:request}).trust,"reported");
    assert.throws(()=>acknowledgementRecord(invoice,{kind:"ewaybill",result,submittedRequest:{...request,totInvValue:590}}),/totInvValue/);
    assert.throws(()=>acknowledgementRecord(invoice,{kind:"ewaybill",result,submittedRequest:{...request,itemList:[{...request.itemList[0],hsnCode:998391}]}}),/goods|item/i);
    const {invoice:onlyService}=await post([{itemId:service.id,quantity:"1"}]);
    assert.throws(()=>ewaybillDocument(onlyService,preparation),/physical goods/);
  });
});

