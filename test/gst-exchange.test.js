test("IRP signed invoice and signed QR are independently bound and never trust a supplied key", async () => {
  await withInvoice(async ({ invoice, preparation }) => {
    const result = resultFor(invoice, preparation);
    const record = acknowledgementRecord(invoice, { kind: "irp", result, publicKey: publicKey.export({ type: "spki", format: "pem" }), trust: "signature-verified" });
    assert.equal(record.trust, "reported");
    assert.equal(record.signature.status, "reported");
    assert.equal(record.qr.signature.status, "reported");
    assert.equal(record.qr.token, result.SignedQRCode);
    assert.equal(record.qr.payload.totalPaise, invoice.totals.totalPaise);
    assert.equal(record.qr.payload.mainHsnCode, invoice.items[0].hsnSac);
    assert.equal(record.reference, PUBLIC_SAMPLE_IRN);
    const state = exchangeView(invoice, { version: 1, preparations: [], acknowledgements: [record] });
    assert.equal(state.display.signedQRCode, result.SignedQRCode);
    assert.equal(state.display.trust, "reported");
    assert.equal(state.display.invoiceSignature.signatureMatches, false);
    assert.equal(state.display.qrSignature.signatureMatches, false);
    assert.equal(IRP_SIGNING_REGISTRY[0].environment, "production");
    assert.equal(IRP_SIGNING_REGISTRY[0].certificate.fingerprint256, IRP_SIGNING_REGISTRY[0].fingerprint256);
  });
});

test("swapped identity, mismatched totals and independently altered QR fields reject", async () => {
  await withInvoice(async ({ invoice, preparation }) => {
    const swapped = resultFor(invoice, preparation, document => ({ ...document, SellerDtls: { ...document.SellerDtls, Gstin: makeGstin("27") } }));
    assert.throws(() => acknowledgementRecord(invoice, { kind: "irp", result: swapped }), /identifiers do not match/);
    const amount = resultFor(invoice, preparation, document => ({ ...document, ValDtls: { ...document.ValDtls, TotInvVal: document.ValDtls.TotInvVal + 0.01 } }));
    assert.throws(() => acknowledgementRecord(invoice, { kind: "irp", result: amount }), /amount TotInvVal/);
    for (const changed of [
      { SellerGstin: makeGstin("27") }, { BuyerGstin: makeGstin("23") }, { DocNo: "OTHER" },
      { DocTyp: "CRN" }, { DocDt: "01/04/2025" }, { TotInvVal: 1 }, { ItemCnt: 99 }, { MainHsnCode: "1001" }, { Irn: "mismatch" },
    ]) {
      const result = resultFor(invoice, preparation, document => document, qr => ({ ...qr, ...changed }));
      assert.throws(() => acknowledgementRecord(invoice, { kind: "irp", result }), /signed QR/);
    }
  });
});

test("invalid JWS algorithms, missing QR and bare EWB results cannot gain invoice binding", async () => {
  await withInvoice(async ({ invoice, preparation }) => {
    const noQr = resultFor(invoice, preparation);
    delete noQr.SignedQRCode;
    assert.throws(() => acknowledgementRecord(invoice, { kind: "irp", result: noQr }), /SignedInvoice and SignedQRCode/);
    const badAlgorithm = resultFor(invoice, preparation);
    badAlgorithm.SignedQRCode = token({}, { alg: "none" });
    assert.throws(() => acknowledgementRecord(invoice, { kind: "irp", result: badAlgorithm }), /RS256/);
    const bare = { ewayBillNo: "123456789012", ewayBillDate: "08/11/2026 12:00:00 PM", validUpto: "09/11/2026 11:59:00 PM" };
    assert.throws(() => acknowledgementRecord(invoice, { kind: "ewaybill", result: bare }), /full document details/);
    const request = ewaybillDocument(invoice, preparation);
    const bound = acknowledgementRecord(invoice, { kind: "ewaybill", result: bare, submittedRequest: request });
    assert.equal(bound.trust, "reported");
    assert.equal(bound.binding, "submitted-request-with-reported-result");
    assert.throws(() => acknowledgementRecord(invoice, { kind: "ewaybill", result: bare, submittedRequest: { ...request, totInvValue: 1 } }), /amount totInvValue/);
    assert.throws(() => acknowledgementRecord(invoice, { kind: "ewaybill", result: bare, submittedRequest: { ...request, fromGstin: makeGstin("27") } }), /identifiers/);
  });
});

test("append-only preparation and acknowledgement retries preserve journal and survive backup", async () => {
  await withInvoice(async ({ store, company, invoice, preparation }) => {
    const before = await store.get(company.id);
    const saved = await store.saveGstExchange(company.id, invoice.id, "preparation", preparation);
    assert.equal(saved.history.preparations.length, 1);
    assert.equal((await store.saveGstExchange(company.id, invoice.id, "preparation", preparation)).replayed, true);
    const result = resultFor(invoice, preparation);
    const payload = { kind: "irp", result };
    const [first, second] = await Promise.all([
      store.saveGstExchange(company.id, invoice.id, "acknowledgement", payload),
      store.saveGstExchange(company.id, invoice.id, "acknowledgement", payload),
    ]);
    assert.equal(first.history.acknowledgements.length, 1);
    assert.equal(second.replayed, true);
    const after = await store.get(company.id);
    assert.deepEqual(after.vouchers[0].lines, before.vouchers[0].lines);
    assert.deepEqual(after.vouchers[0].gst, before.vouchers[0].gst);
    const backup = companyBackup(after.company, after.vouchers);
    const restored = validateTransfer(backup);
    assert.equal(restored.vouchers[0].gstExchange.acknowledgements.length, 1);
    assert.equal(restored.vouchers[0].gstExchange.acknowledgements[0].qr.token, result.SignedQRCode);
    const changed = structuredClone(first.history);
    changed.acknowledgements[0].trust = "signature-verified";
    changed.acknowledgements[0].signature.status = "signature-verified";
    assert.equal(assertExchangeSnapshot(invoice, changed).acknowledgements[0].trust, "reported");
    const duplicate = { ...result, AckDt: `${invoice.date} 12:01:00` };
    await assert.rejects(store.saveGstExchange(company.id, invoice.id, "acknowledgement", { kind: "irp", result: duplicate }), /already linked/);
  });
});

test("HTTP preparation, attachment downloads and acknowledgement binding round trip", async () => {
  await withInvoice(async ({ dataDir, company, invoice, preparation }) => {
    const server = await start({ dataDir });
    const base = `http://127.0.0.1:${server.address().port}/api/companies/${company.id}/gst-exchange/${invoice.id}`;
    try {
      const saved = await fetch(base, { method: "PUT", headers: { "content-type": "application/json" }, body: JSON.stringify(preparation) });
      assert.equal(saved.status, 200);
      const state = await saved.json();
      assert.equal(state.capabilities.irp.ready, true);
      assert.equal(state.capabilities.ewaybill.ready, true);
      for (const endpoint of ["irp", "ewaybill"]) {
        const response = await fetch(`${base}/${endpoint}`);
        assert.equal(response.status, 200);
        assert.match(response.headers.get("content-disposition"), /attachment/);
        const document = await response.json();
        assert.equal(endpoint === "irp" ? document[0].DocDtls.No : document.docNo, invoice.number);
      }
      const imported = await fetch(`${base}/acknowledgements`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ kind: "irp", result: resultFor(invoice, preparation) }) });
      assert.equal(imported.status, 201);
      assert.equal((await imported.json()).display.trust, "reported");
      const response = await fetch(base);
      assert.equal((await response.json()).history.acknowledgements.length, 1);
    } finally { await new Promise(resolve => server.close(resolve)); }
  });
});

test("registered outward RCM exports recipient liability and only binds the matching reverse-charge flag", async () => {
  await withInvoice(async ({ store, company, invoice: base, preparation }) => {
    const { invoice, voucher } = await store.passGstInvoice(company.id, {
      type: "Sales", registrationId: base.registrationId, partyId: base.partyId,
      date: base.date, placeOfSupply: base.placeOfSupply, pricing: "exclusive", reverseCharge: true,
      rcm: { applicabilityConfirmed: true, basisReference: "Synthetic notified supply" },
      items: [{ itemId: base.items[0].itemId, quantity: "2", unitPricePaise: 10000 }],
    });
    const [document] = irpBulk(invoice, preparation);
    assert.equal(document.TranDtls.RegRev, "Y");
    assert.equal(document.ValDtls.TotInvVal, 236);
    assert.equal(invoice.partyDuePaise, 20000);
    assert.equal(voucher.lines.length, 2);
    const record = acknowledgementRecord(invoice, { kind: "irp", result: resultFor(invoice,preparation) });
    assert.equal(record.invoiceFingerprint.length, 64);
    const wrongFlag = resultFor(invoice, preparation, doc => ({ ...doc, TranDtls: { ...doc.TranDtls, RegRev: "N" } }));
    assert.throws(() => acknowledgementRecord(invoice, { kind: "irp", result: wrongFlag }), /reverse-charge flag/);
    assert.throws(() => ewaybillDocument(invoice, preparation), /reverse-charge e-way bill/);
  });
});

test("the exchange route switches from combined IRP + transport to an IRN-only request and binds the returned EWB", async () => {
  await withInvoice(async ({dataDir,store,company,invoice,preparation})=>{
    await store.saveGstMaster(company.id,"irpPolicy",{registrationId:invoice.registrationId,effectiveFrom:invoice.date,status:"required",thirtyDayWindow:true});
    await store.saveGstExchange(company.id,invoice.id,"preparation",preparation);
    const server=await start({dataDir});
    const endpoint=`http://127.0.0.1:${server.address().port}/api/companies/${company.id}/gst-exchange/${invoice.id}`;
    try {
      const state=async()=>await (await fetch(endpoint)).json();
      const file=async()=>await (await fetch(endpoint+"/ewaybill")).json();
      assert.equal((await state()).movementMode,"combined");
      const combined=(await file())[0];
      assert.equal(combined.EwbDtls.VehNo,"MP04AB1234");
      assert.equal(combined.EwbDtls.Distance,700);
      assert.equal(combined.DocDtls.No,invoice.number);
      await store.saveGstExchange(company.id,invoice.id,"acknowledgement",{kind:"irp",result:resultFor(invoice,preparation)});
      assert.equal((await state()).movementMode,"by-irn");
      const request=await file();
      assert.equal(request.Irn,PUBLIC_SAMPLE_IRN);
      assert.equal(request.VehType,"R");
      assert.equal(request.DocDtls,undefined);
      const result={EwbNo:111008683051,EwbDt:invoice.date+" 11:28:00",EwbValidTill:invoice.date+" 23:59:00"};
      await assert.rejects(store.saveGstExchange(company.id,invoice.id,"acknowledgement",{kind:"ewaybill",result,submittedRequest:{...request,Irn:"f".repeat(64)}}),/does not match an imported/);
      await store.saveGstExchange(company.id,invoice.id,"acknowledgement",{kind:"ewaybill",result,submittedRequest:request});
      assert.equal((await state()).capabilities.ewaybill.ready,false);
      assert.equal((await fetch(endpoint+"/ewaybill")).status,400);
      const {company:owner,vouchers}=await store.get(company.id);
      assert.deepEqual(validateTransfer(companyBackup(owner,vouchers)).vouchers,vouchers);
    } finally { await new Promise(resolve=>server.close(resolve)); }
  });
});
