"""Run against a disposable Financer specimen server. No vouchers are posted."""
import argparse
import os
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
parser = argparse.ArgumentParser()
parser.add_argument("url", help="Loopback URL of an isolated Financer specimen server")
parser.add_argument("--browser", default=os.environ.get("LEDGERCRAFT_TEST_BROWSER") or os.environ.get("FINANCER_TEST_BROWSER"), help="Path to an already installed local Chromium executable")
args = parser.parse_args()
from urllib.parse import urlparse
if urlparse(args.url).hostname not in {"localhost", "127.0.0.1"}:
    parser.error("Use a local test instance")
URL = args.url.rstrip("/")
chrome = args.browser
with sync_playwright() as p:
 b=p.chromium.launch(executable_path=chrome,headless=True,args=['--disable-background-networking','--disable-component-update','--no-first-run','--disable-sync','--disable-breakpad'])
 page=b.new_page()
 errors=[]
 page.on('pageerror',lambda err:errors.append(str(err)))
 page.route('**/*', lambda route:route.continue_() if route.request.url.startswith(URL+'/') else route.abort())
 page.goto(URL)
 page.get_by_role('heading',name='Owner review',exact=True).wait_for()
 expect(page.get_by_text('New voucher',exact=True)).to_have_count(1)
 page.get_by_text('New voucher',exact=True).click()
 page.get_by_role('link',name='Receipt',exact=True).click()
 act=page.locator('#line-action')
 expect(act).to_contain_text('Add line')
 expect(page.locator('#add-line,#balance-line')).to_have_count(0)
 expect(page.locator('#lines tr')).to_have_count(2)
 page.locator('#ledger-0').select_option('l-cash')
 page.locator('#dr-0').fill('12')
 expect(page.locator('#cr-0')).to_be_disabled(timeout=1500)
 expect(page.locator('#cr-1')).to_be_enabled()
 page.locator('#dr-0').fill('')
 expect(page.locator('#cr-0')).to_be_enabled()
 page.locator('#cr-0').fill('5')
 expect(page.locator('#dr-0')).to_be_disabled()
 page.locator('#cr-0').fill('')
 expect(page.locator('#dr-0')).to_be_enabled()
 page.context.grant_permissions(['clipboard-read','clipboard-write'],origin=URL)
 page.evaluate("navigator.clipboard.writeText('1200.01')")
 page.locator('#dr-0').focus()
 page.keyboard.press('Meta+v')
 expect(page.locator('#dr-0')).to_have_value('1200.01')
 expect(page.locator('#cr-0')).to_be_disabled()
 expect(act).to_contain_text('Fill credit ₹1,200.01')
 act.click()
 expect(page.locator('#lines tr')).to_have_count(2)
 expect(page.locator('#cr-1')).to_have_value('1,200.01')
 expect(page.locator('#dr-1')).to_be_disabled()
 page.locator('#ledger-1').select_option('l-sales')
 expect(page.locator('[data-pass]')).to_be_enabled()
 expect(act).to_contain_text('Add line')
 act.click()
 expect(page.locator('#lines tr')).to_have_count(3)
 page.locator('#cr-1').fill('1000')
 expect(act).to_contain_text('Fill credit ₹200.01')
 page.locator('#cr-1').press('Alt+Enter')
 expect(page.locator('#cr-2')).to_have_value('200.01')
 page.get_by_role('link',name='Owner review',exact=True).click()
 page.get_by_role('link',name='Net payables',exact=False).click()
 page.get_by_role('heading',name='Payables',exact=True).wait_for()
 expect(page.get_by_role('heading',name='Sundry debtors',exact=True)).to_have_count(0)
 page.get_by_role('link',name='Owner review',exact=True).click()
 page.get_by_role('link',name='RCT-1',exact=True).click()
 page.get_by_role('heading',name='Alter RCT-1',exact=True).wait_for()
 expect(page.locator('#cr-0')).to_be_disabled()
 expect(page.locator('#dr-1')).to_be_disabled()
 expect(page.locator('#dr-0')).to_be_enabled()
 expect(page.locator('#cr-1')).to_be_enabled()
 page.locator('#cr-1').fill('')
 expect(page.locator('#dr-1')).to_be_enabled()
 assert not errors,errors
 print('Debit and credit lock and unlock independently after typing, pasting, automatic balancing and reopening a voucher. Owner review has one voucher menu. Single receipt action: blank/add, missing credit/fill existing, balanced/append, Option+Return fill. Payables drilldown shows creditors only. No JS errors.')
 b.close()
