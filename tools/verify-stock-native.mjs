import assert from 'node:assert/strict';
import { runNative } from './native-command.mjs';
import { createHash } from 'node:crypto';
import { cp, mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const scratch = await mkdtemp(path.join(tmpdir(), 'financer-stock-native-'));
const output = path.resolve(process.argv[2] || path.join(root, 'output', 'stock-native-proof'));
await mkdir(output, { recursive: true });
const run = args => runNative(args, root);
let server;
try {
  const frozen = path.join(scratch, 'source');
  await mkdir(frozen);
  for (const name of ['package.json', 'server.js', 'lib', 'public']) await cp(path.join(root, name), path.join(frozen, name), { recursive: true });
  const { createStore } = await import(pathToFileURL(path.join(frozen, 'lib/store.js')));
  const { start } = await import(pathToFileURL(path.join(frozen, 'server.js')));
  const { gstinCheckDigit } = await import(pathToFileURL(path.join(frozen, 'lib/gst.js')));
  const gstin = (state, pan) => { const prefix = `${state}${pan}1Z`; return prefix + gstinCheckDigit(prefix); };
  const store = createStore(path.join(scratch, 'data'));
  const { company } = await store.create({ name: 'Synthetic Stock Native UI', booksFrom: '2026-04-01' });
  const registration = (await store.saveGstMaster(company.id, 'registration', { name: 'Synthetic Supplier', legalName: 'Synthetic Supplier', gstin: gstin('23', 'ABCDE1234F'), stateCode: '23', address: 'Synthetic supplier, Bhopal', pincode: '462001' })).registration;
  const party = (await store.saveGstMaster(company.id, 'party', { name: 'Synthetic Customer', kind: 'customer', gstin: gstin('27', 'PQRST5678L'), stateCode: '27', address: 'Synthetic customer, Mumbai', pincode: '400001' })).party;
  const makeItem = (name, kind, openingQuantity, pricePaise) => store.saveGstMaster(company.id, 'item', { name, kind, openingQuantity, pricePaise, purchasePricePaise: 8000, gstRateBps: 1800, cessRateBps: 0, hsnSac: kind === 'goods' ? '854140' : '998599', unit: 'NOS', supplyStatus: 'taxable' });
  const fasteners = (await makeItem('Synthetic fasteners', 'goods', '10', 10000)).item;
  const spares = (await makeItem('Unpriced spares', 'goods', '2', 99900)).item;
  const service = (await makeItem('Synthetic handling', 'service', '0', 1000)).item;
  await store.saveGstMaster(company.id, 'turnover', { registrationId: registration.id, year: '2026', band: 'up-to-5cr' });
  await store.addLedger(company.id, { name: 'Opening stock control', groupId: 'g-stock', openingPaise: 12000, openingDc: 'Dr' });
  await store.addLedger(company.id, { name: 'Synthetic capital', groupId: 'g-capital', openingPaise: 12000, openingDc: 'Cr' });
  await store.mutateCompanySection(company.id, 'stock', () => ({ version: 1, revision: 0, integrateAccounts: false, godowns: [{ id: 'main', name: 'Main Location' }], items: { [fasteners.id]: { costingMethod: 'fifo', openingValuePaise: 10000, openingAllocations: [{ godownId: 'main', quantity: '10', valuePaise: 10000 }] } }, journals: [] }));
  server = await start({ dataDir: path.join(scratch, 'data') });
  const base = `http://127.0.0.1:${server.address().port}`;
  const config = path.join(scratch, 'fixture.json');
  await writeFile(config, JSON.stringify({ base, company: company.id, registration: registration.id, party: party.id, fasteners: fasteners.id, spares: spares.id, service: service.id, output }));
  const executable = path.join(scratch, 'financer-stock-ui');
  await run(['/usr/bin/swiftc', '-swift-version', '5', path.join(root, 'test/stock-ui.swift'), '-o', executable, '-framework', 'AppKit', '-framework', 'WebKit', '-framework', 'PDFKit']);
  await run([executable, config]);
  const endpoint = `${base}/api/companies/${company.id}`;
  const stock = await (await fetch(endpoint + '/stock?from=2026-04-01&to=2026-04-30')).json();
  assert.equal(stock.settings.integrateAccounts, true);
  assert.equal(stock.financialCheck.reason, '');
  assert.equal(stock.journals.length, 3);
  assert.deepEqual(stock.journals.map(journal => journal.type).sort(), ['transfer', 'adjustment', 'physical'].sort());
  const fastenerStock = stock.items.find(item => item.itemId === fasteners.id);
  assert.equal(fastenerStock.costingMethod, 'moving-average');
  assert.equal(fastenerStock.quantity, '9');
  assert.equal(fastenerStock.valuePaise, 9450);
  assert.equal(stock.items.find(item => item.itemId === spares.id).valuePaise, 2000);
  assert.equal(stock.totals.valuePaise, 11450);
  assert.equal(stock.items.some(item => item.itemId === service.id), false);
  const current = await (await fetch(endpoint)).json();
  assert.equal(current.vouchers.length, 1);
  assert.equal(current.vouchers[0].gst.totals.totalPaise, 12980);
  assert.equal(current.vouchers[0].stock.lines.length, 1);
  const annex = stock.godowns.find(godown => godown.name === 'Annex');
  assert.equal(current.vouchers[0].stock.lines[0].allocations[0].godownId, annex.id);
  assert.equal(fastenerStock.godowns.find(godown => godown.godownId === annex.id).quantity, '1');
  const sourceSHA256 = {};
  for (const name of ['public/stock-ui.js', 'public/stock-ui.css', 'public/gst-ui.js', 'lib/stock-engine.js', 'lib/stock-routes.js']) sourceSHA256[name] = createHash('sha256').update(await readFile(path.join(frozen, name))).digest('hex');
  await writeFile(path.join(output, 'backend-results.json'), JSON.stringify({ passed: true, environment: 'isolated local synthetic books and frozen source/assets', costingMethod: fastenerStock.costingMethod, fastenerQuantity: fastenerStock.quantity, fastenerValuePaise: fastenerStock.valuePaise, totalStockValuePaise: stock.totals.valuePaise, journalTypes: stock.journals.map(row => row.type), journalCount: stock.journals.length, gstVouchers: 1, invoiceTotalPaise: 12980, serviceExcluded: true, financialIntegrationExplicitlySaved: true, openingLedgersMatch: true, invoiceGodownMetadata: current.vouchers[0].stock, sourceSHA256 }, null, 2));
  await run([executable, config, "--print-only"]);
  await run([process.env.LEDGERCRAFT_PYTHON || 'python3', path.join(root, "test/stock-print-check.py"), output]);
  console.log(`Native stock proof saved to ${output}`);
} finally {
  if (server) { server.closeIdleConnections(); await new Promise(resolve => server.close(resolve)); }
  await rm(scratch, { recursive: true, force: true });
}
